"""
Converts a model prediction (class + confidence) into a structured,
human-readable report, and provides an optional dynamic-thresholding
function for malignant sensitivity tuning.
"""

from datetime import datetime

CLASS_NAMES = ["normal", "benign", "malignant"]
MALIGNANT_IDX = CLASS_NAMES.index("malignant")

RECOMMENDATION = {
    "normal": "No suspicious findings detected. Routine follow-up as per standard care.",
    "benign": "Findings suggest a benign lesion. Clinical correlation and short-interval "
              "follow-up ultrasound recommended to confirm stability.",
    "malignant": "Findings suggest possible malignancy. Urgent referral for biopsy and "
                 "specialist radiologist review is recommended.",
}

DISCLAIMER = (
    "This report was generated by an AI research prototype. It is NOT a certified "
    "medical diagnosis and must not be used as the sole basis for clinical decisions. "
    "All findings should be reviewed and confirmed by a licensed radiologist or physician."
)


def predict_with_sensitivity(probabilities, malignant_threshold=0.35):
    """
    Instead of always picking the single highest-probability class (argmax),
    flag a scan as malignant if its malignant probability alone clears a
    lower bar (e.g. 0.35 instead of the implicit 0.5 that argmax uses).

    Rationale: in a screening context, a false negative (missing a real
    malignancy) is far costlier than a false positive (an unnecessary
    follow-up). Lowering the malignant threshold trades some precision for
    higher sensitivity/recall on the malignant class. This is a deliberate,
    documented trade-off, not a free accuracy improvement -- the chosen
    threshold should always be reported alongside any accuracy numbers.

    probabilities: list/array of 3 floats (normal, benign, malignant), summing to ~1
    malignant_threshold: if malignant probability >= this, predict malignant
                          regardless of whether another class scored higher

    Returns: (predicted_class_idx, malignant_probability)
    """
    malignant_prob = probabilities[MALIGNANT_IDX]
    if malignant_prob >= malignant_threshold:
        predicted_class = MALIGNANT_IDX
    else:
        predicted_class = max(range(len(probabilities)), key=lambda i: probabilities[i])
    return predicted_class, malignant_prob


def generate_report(predicted_class_idx, confidence, patient_id=None, scan_id=None,
                     malignant_threshold=None):
    """
    predicted_class_idx: int, index into CLASS_NAMES
    confidence: float in [0, 1], model's confidence in the predicted class
    patient_id / scan_id: optional identifiers for the report header
    malignant_threshold: if a non-default threshold was used to make this
                          prediction (via predict_with_sensitivity), pass it
                          here so it's disclosed in the report
    """
    predicted_class = CLASS_NAMES[predicted_class_idx]
    confidence_pct = round(confidence * 100, 1)

    if confidence_pct < 60:
        confidence_note = ("Model confidence is low — this result should be treated as "
                            "inconclusive and reviewed manually.")
    else:
        confidence_note = ""

    report_lines = [
        "=" * 60,
        "AI-ASSISTED ULTRASOUND SCREENING REPORT (PROTOTYPE)",
        "=" * 60,
        f"Generated: {datetime.now().strftime('%Y-%m-%d %H:%M')}",
    ]
    if patient_id:
        report_lines.append(f"Patient ID: {patient_id}")
    if scan_id:
        report_lines.append(f"Scan ID: {scan_id}")

    report_lines += [
        "",
        f"Finding: {predicted_class.upper()}",
        f"Model Confidence: {confidence_pct}%",
    ]
    if confidence_note:
        report_lines.append(f"Note: {confidence_note}")
    if malignant_threshold is not None:
        report_lines.append(
            f"Sensitivity mode: malignant flagged at probability >= {malignant_threshold:.0%} "
            f"(lower than standard 50% threshold, favoring higher recall)"
        )

    report_lines += [
        "",
        f"Recommendation: {RECOMMENDATION[predicted_class]}",
        "",
        "-" * 60,
        DISCLAIMER,
        "=" * 60,
    ]

    return "\n".join(report_lines)
